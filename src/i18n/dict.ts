const DICTS: Record<LangCode, Dict> = { en, id, ar, ja, zh, vi };

export function translate(
  lang: LangCode,
  key: string,
  vars?: Record<string, string>
): string {
  let s = DICTS[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}
